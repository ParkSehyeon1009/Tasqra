export const AUTO_NOTE_MARKER = '── 자동 기록 ──'

/** 설명을 [사람이 쓴 부분, 자동 기록] 으로 나눈다.
 *
 *  자동 기록이 없으면 두 번째가 빈 문자열이다. 구분자가 여러 번 있으면
 *  **처음 것**에서 나눈다 — 서버가 늘 마지막 블록만 남기므로 정상적으로는 하나뿐이고,
 *  사람이 실수로 같은 글자를 적었더라도 사람이 쓴 것을 먼저 보여주는 쪽이 안전하다.
 */
export function splitAutoNote(text) {
  if (!text) return ['', '']
  const at = text.indexOf(AUTO_NOTE_MARKER)
  if (at === -1) return [text, '']
  return [
    text.slice(0, at).trimEnd(),
    text.slice(at + AUTO_NOTE_MARKER.length).trim(),
  ]
}
