//   유틸 클래스(JSP 의 커스텀 태그 함수) 자리다.
//
// ⚠ 표시 문자열이 백엔드와 **글자까지 같아야 한다**
//   backend/app/services/task_service.py 의 AUTO_NOTE_MARKER 와 한 글자라도
//   다르면 블록을 못 찾아서 색이 안 입고 그냥 본문에 섞여 나온다. 에러가 나지
//   않으므로 알아채기 어렵다. 한쪽을 고치면 **반드시 다른 쪽도** 고친다.
//
//   상수를 한 곳에 두지 못하는 이유: 백엔드는 파이썬이고 화면은 자바스크립트라
//   같은 파일을 공유할 수 없다. 서버가 응답에 구분자를 실어 보내는 방법도 있지만,
//   설명은 그냥 텍스트 컬럼이라 그러려면 태스크 응답 모양을 바꿔야 한다.
